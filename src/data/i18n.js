export function localizedPath(path, lang = 'de') {
  if (lang === 'en') {
    if (path === '/') return '/en/';
    if (path === '/ratgeber/') return '/en/guide/';
    if (path === '/handbuch/') return '/en/manual/';
    return path;
  }
  return path;
}
